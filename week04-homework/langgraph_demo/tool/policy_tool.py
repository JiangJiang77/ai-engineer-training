from langchain.tools import tool


@tool
def get_policy_detail() -> str:
    """
    获取政策详情
    """

    return """
        ## 1. 售后政策 (After-sales Policy)

        售后规则通常是用户检索频率最高的部分。

        * **退换货时效：** 标配通常为“自签收之日起 7 天无理由退货，15 天换货”。特殊类目（如内衣、食品、数字化商品）除外。
        * **退款路径：** 原路返回（支付工具）、返还至余额或银行卡。
        * **退款时效：** 商家审核通过后，通常 1-3 个工作日到账。
        * **运费承担：** 质量问题由商家承担；非质量问题（不喜欢、拍错）由买家承担。

        ## 2. 物流政策 (Logistics Policy)

        * **发货时效：** 现货订单通常 24-48 小时内发货；预售商品以页面公示日期为准。
        * **配送范围：** 明确哪些偏远地区不发货或需补运费（如新疆、西藏、港澳台）。
        * **签收规范：** 提醒用户需当面验货。若包装破损，应拍照取证并拒收。
        * **虚假发货界定：** 点击“发货”后 X 小时内无物流揽收记录的补偿标准。

        ## 3. 支付政策 (Payment Policy)

        * **支持渠道：** 微信支付、支付宝、银联、数字人民币或平台积分抵扣。
        * **支付时效：** 订单提交后未在 30 分钟（或自定义时长）内支付，系统将自动取消订单并释放库存。
        * **安全验证：** 大额支付可能触发的风控逻辑（如手机验证码验证）。

        ## 4. 质保与保修 (Warranty Policy)

        * **保修期限：** 国家“三包”政策为基础，特定电子产品提供 1-3 年质保。
        * **非保修范围：** 人为损坏、私自拆解、不可抗力（水灾、火灾）等。
        * **保修凭证：** 需提供有效发票、保修卡或系统内的电子订单记录。

        ---

        ## 5. 订单状态流转 (Order Status Workflow)

        这是后台逻辑的核心，建议以“状态 - 定义 - 下一步动作”的形式存储。

        | 状态名称 | 触发条件 | 可执行操作 |
        | --- | --- | --- |
        | **待付款** | 用户提交订单后 | 支付、取消订单、修改地址 |
        | **待发货** | 用户支付成功后 | 申请退款、修改联系方式 |
        | **已发货** | 商家录入物流单号后 | 查看物流、确认收货、申请售后 |
        | **已完成** | 用户确认收货或系统自动确认后 | 评价、申请售后、申请开票 |
        | **已关闭** | 超时未支付或全额退款完成后 | 查看详情（无法再操作） |

        ---

        ## 6. 发票政策 (Invoicing Policy)

        * **发票类型：** 增值税普通发票（电子/纸质）、增值税专用发票（需资质审核）。
        * **开具时间：** 订单完成（确认收货）后方可申请。
        * **发票内容：** 默认展示商品明细，不可修改为其他类目。
        * **重开逻辑：** 若信息填写错误，需在 X 天内联系客服退回原票并重开。
            """
